"""Reproducible M4-M7 scorecard and PR evidence, generated from real evals.

Run from src/: python -m lab9.verify
Does not edit agent code, thresholds, variants or traps.
"""

import copy
import json
from pathlib import Path

import yaml

from lab8.console import utf8_stdio
from lab9 import gate, stats, traps, variants
from lab9.eval import load_spec, per_item, run_eval
from lab9.mutation import EXPECTED


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")


def main():
    utf8_stdio()
    variants.register()
    spec1 = load_spec(Path("config/metric_spec.yaml"))
    spec2 = load_spec(Path("config/metric_spec_v2.yaml"))
    base1 = json.loads(Path("reports/baseline_v1.json").read_text(encoding="utf-8"))
    base2 = json.loads(Path("reports/baseline_v2.json").read_text(encoding="utf-8"))
    result = {"command": "python -m lab9.verify", "core": {}, "variants": {}, "traps": {}}
    for name in ("fixed", "seeded_regression"):
        pr = json.loads(Path(f"reports/eval_{name}.json").read_text(encoding="utf-8"))
        blocked, lines = gate.check(pr, base1, spec1, spec1)
        a, b = per_item(pr, "pass_rate"), per_item(base1, "pass_rate")
        keys = sorted(a)
        result["core"][name] = {"run_id": pr["run_id"], "blocked": blocked, "lines": lines,
            "exit_code": int(bool(blocked)),
            "pass_rate_ci": stats.paired_bootstrap([a[k] for k in keys], [b[k] for k in keys])}
    result["self_comparison"] = gate.check(base2, base2, spec2, spec2)[0]
    for name, expected in EXPECTED.items():
        pr = run_eval(name, spec2)
        write(Path(f"reports/eval_v2_{name}.json"), pr)
        blocked, lines = gate.check(pr, base2, spec2, spec2)
        result["variants"][name] = {"run_id": pr["run_id"], "expected": expected,
            "actual": "block" if blocked else "merge", "blocked": blocked,
            "metrics": pr["metrics"], "lines": lines}
        print(name, result["variants"][name]["actual"], blocked, flush=True)
    alternate = run_eval("swarm", spec2, [66, 77, 88, 99, 110])
    write(Path("reports/aa_alternate.json"), alternate)
    result["aa"] = {"base_run_id": base2["run_id"], "alternate_run_id": alternate["run_id"],
        "seeds": alternate["manifest"]["seeds"],
        "deltas": {key: value - base2["metrics"][key] for key, value in alternate["metrics"].items()
                   if isinstance(value, (int, float)) and isinstance(base2["metrics"].get(key), (int, float))}}
    broken = json.loads(Path("reports/eval_v2_slice_regression.json").read_text(encoding="utf-8"))
    out = Path("reports/traps")
    out.mkdir(exist_ok=True)
    for name, (pr, loose) in traps.build(broken, spec2).items():
        write(out / f"{name}.json", pr)
        if loose is not None:
            (out / f"{name}.spec.yaml").write_text(yaml.safe_dump(loose, sort_keys=False), encoding="utf-8")
        blocked, lines = gate.check(pr, base2, loose or spec2, spec2)
        result["traps"][name] = {"exit_code": int(bool(blocked)), "blocked": blocked, "lines": lines}
    # Extra generic traps: public harness hints at duplicates and grader failures on green runs.
    for name in ("duplicate_row", "evaluator_failure_on_green", "relabeled_slice"):
        pr = copy.deepcopy(base2)
        if name == "duplicate_row":
            pr["rows"][-1] = copy.deepcopy(pr["rows"][0])
        elif name == "evaluator_failure_on_green":
            pr["evaluator_failures"] = ["synthetic grader failure on an otherwise green-looking report"]
        else:
            for row in pr["rows"]:
                row["slices"] = []
        blocked, lines = gate.check(pr, base2, spec2, spec2)
        result["traps"][name] = {"exit_code": int(bool(blocked)), "blocked": blocked, "lines": lines}
    regressions = [r for r in result["variants"].values() if r["expected"] == "block"]
    result["mutation_score"] = f"{sum(r['actual'] == 'block' for r in regressions)}/{len(regressions)}"
    result["false_alarms"] = sum(r["expected"] == "merge" and r["actual"] == "block"
                                  for r in result["variants"].values())
    success = (not result["core"]["fixed"]["blocked"]
               and "pass_rate" in result["core"]["seeded_regression"]["blocked"]
               and not result["self_comparison"]
               and all(r["actual"] == r["expected"] for r in result["variants"].values())
               and all(r["exit_code"] == 1 for r in result["traps"].values()))
    result["passed"] = success
    write(Path("reports/verification.json"), result)
    evidence = ["# PR evidence — generated by python -m lab9.verify", "",
                "Report: src/reports/verification.json", "", "## Core gate"]
    for name, r in result["core"].items():
        evidence += [f"### {name}", "```text", *r["lines"],
                     f"exit {r['exit_code']} — " + ("blocked: " + ", ".join(r["blocked"]) if r["blocked"] else "merge"), "```"]
    evidence += ["", "## Mutation scorecard", "```text"]
    for name, r in result["variants"].items():
        evidence.append(f"{name}: expect {r['expected']}, got {r['actual']}; {', '.join(r['blocked'])}".rstrip())
    evidence += [f"mutation score {result['mutation_score']}; false alarms {result['false_alarms']}", "```",
                 "", "## A/A deltas", "```text", *[f"{k}: {v:+.4f}" for k, v in result["aa"]["deltas"].items()], "```",
                 "", "## Traps", "```text"]
    evidence += [f"{name}: exit {r['exit_code']} — {', '.join(r['blocked'])}" for name, r in result["traps"].items()]
    evidence += ["```", "", "These are local checks; GitHub Actions status is verified after opening the PR."]
    Path("../docs/pr_evidence.md").write_text("\n".join(evidence) + "\n", encoding="utf-8")
    print("mutation score", result["mutation_score"], "false alarms", result["false_alarms"])
    print("A/A", result["aa"]["deltas"])
    print("verification", "PASS" if success else "FAIL")
    return 0 if success else 1


if __name__ == "__main__":
    raise SystemExit(main())
